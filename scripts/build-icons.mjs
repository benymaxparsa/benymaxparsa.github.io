// Generates src/styles/icons.css: the Font Awesome 5 / Academicons glyphs the site
// uses, as CSS masks keyed on the same class names (`<i class="fas fa-envelope">`),
// so content keeps its markup without loading an icon font or CDN.
// To add an icon: append its class to ICONS and run `node scripts/build-icons.mjs`.
// Glyph sources are the SVG fonts in fonts/ (FA Free: CC BY 4.0; Academicons: SIL OFL 1.1).
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  'fa-envelope', 'fa-envelope-square', 'fa-envelope-open', 'fa-link', 'fa-download', 'fa-file-download',
  'fa-folder-open', 'fa-home', 'fa-sitemap', 'fa-trophy', 'fa-info-circle', 'fa-hourglass-half',
  'fa-map-marker-alt', 'fa-graduation-cap', 'fa-briefcase', 'fa-chalkboard-teacher', 'fa-search',
  'fa-calendar-alt', 'fa-github', 'fa-linkedin', 'fa-twitter', 'fa-twitter-square', 'fa-facebook',
  'fa-orcid', 'fa-researchgate', 'fa-youtube', 'fa-mastodon', 'fa-kaggle',
  'ai-google-scholar-square', 'ai-researchgate-square', 'ai-acmdl', 'ai-scopus-square', 'ai-dblp-square',
  'ai-academia-square', 'ai-semantic-scholar', 'ai-stackoverflow',
];

function font(file) {
  const svg = readFileSync(new URL(`../fonts/${file}`, import.meta.url), 'utf8');
  const em = +svg.match(/units-per-em="([\d.]+)"/)[1];
  const ascent = +svg.match(/ascent="([\d.]+)"/)[1];
  const defAdv = +svg.match(/<font[^>]*horiz-adv-x="([\d.]+)"/)[1];
  const glyphs = new Map();
  for (const [g] of svg.matchAll(/<glyph\b[^>]*?\/>/gs)) {
    const name = g.match(/glyph-name="([^"]+)"/)?.[1];
    const d = g.match(/\sd="([^"]+)"/)?.[1];
    if (name && d) glyphs.set(name, { d, adv: +(g.match(/horiz-adv-x="([\d.]+)"/)?.[1] ?? defAdv) });
  }
  return { em, ascent, glyphs };
}

const fa = ['fa-solid-900.svg', 'fa-brands-400.svg', 'fa-regular-400.svg'].map(font);
const ai = [font('academicons.svg')];

let css = `/* Generated by scripts/build-icons.mjs — do not edit by hand. */
.fa, .fas, .far, .fab, .ai {
  display: inline-block;
  height: 1em;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--icon) center / contain no-repeat;
  mask: var(--icon) center / contain no-repeat;
}
.fa-fw, .ai-fw { width: 1.25em; }
`;
for (const cls of ICONS) {
  const name = cls.replace(/^(fa|ai)-/, '');
  // the vendored FA font predates some brand glyphs (orcid); Academicons has them
  const fonts = cls.startsWith('ai-') ? ai : [...fa, ...ai];
  const f = fonts.find((x) => x.glyphs.has(name));
  if (!f) throw new Error(`no glyph for ${cls}`);
  const { d, adv } = f.glyphs.get(name);
  // integer coordinates are sub-pixel at icon size (512–2048 units per em)
  const path = d.trim().replace(/-?\d*\.?\d+(?:e-?\d+)?/g, (n) => String(Math.round(+n))).replace(/\s+/g, ' ').replace(/ ?([A-Za-z]) ?/g, '$1').replace(/ -/g, '-');
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${adv} ${f.em}'><path transform='matrix(1 0 0 -1 0 ${Math.round(f.ascent)})' d='${path}'/></svg>`;
  css += `.${cls} { --icon: url("data:image/svg+xml,${svg.replace(/[%#<>"]/g, encodeURIComponent)}"); }\n`;
  css += `.${cls}:not(.fa-fw):not(.ai-fw) { width: ${+(adv / f.em).toFixed(4)}em; }\n`;
}
writeFileSync(new URL('../src/styles/icons.css', import.meta.url), css);
console.log(`${ICONS.length} icons -> src/styles/icons.css (${(css.length / 1024).toFixed(1)} KB)`);
